import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createApplication } from '../server.mjs';

test('envio, revisão e mostra respeitam identidade, sessão e etapa',async t=>{
  const directory=await mkdtemp(path.join(tmpdir(),'foto-activity-test-'));
  const app=createApplication({dataDir:directory,adminKey:'test-key-only-not-for-production'});
  await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${app.server.address().port}`;
  t.after(async()=>{await app.close();const target=path.resolve(directory);if(path.dirname(target)===path.resolve(tmpdir())&&path.basename(target).startsWith('foto-activity-test-'))await rm(target,{recursive:true,force:true});});
  const call=async(route,token,body)=>{
    const response=await fetch(base+route,{method:body===undefined?'GET':'POST',headers:{...(token?{Authorization:`Bearer ${token}`}:{ }),...(body===undefined?{}:{'Content-Type':'application/json'})},body:body===undefined?undefined:JSON.stringify(body)});
    const result=await response.json();return {status:response.status,...result};
  };
  const admin=app.adminKey;
  assert.equal((await call('/api/admin/sessions','wrong')).status,401);
  const created=await call('/api/admin/sessions',admin,{title:'Turma de teste'}),session=created.session;
  const another=await call('/api/admin/sessions',admin,{title:'Outra turma'});
  await call(`/api/admin/session/${session.id}/groups`,admin,{count:2});
  const groups=(await call(`/api/state/${session.id}`,admin)).groups;
  const participants=(await call(`/api/admin/session/${session.id}/codes`,admin,{count:2})).codes;
  assert.ok(participants.every(person=>person.code.startsWith('P-')));
  const a=await call('/api/join',null,{sessionCode:session.code,accessCode:participants[0].code,groupId:groups[0].id});
  const b=await call('/api/join',null,{sessionCode:session.code,accessCode:participants[1].code,groupId:groups[1].id});
  assert.equal((await call(`/api/state/${another.session.id}`,a.token)).status,403);
  assert.equal((await call('/api/submissions',a.token,{title:'Inválida',image:'data:image/svg+xml;base64,PHN2Zz4='})).status,400);
  const image='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==';
  await call('/api/submissions',a.token,{title:'Foto A',image});
  await call('/api/submissions',b.token,{title:'Foto B',image});
  const reviewed=await call(`/api/state/${session.id}`,admin),photoA=reviewed.photos.find(p=>p.group_id===groups[0].id),photoB=reviewed.photos.find(p=>p.group_id===groups[1].id);
  assert.equal((await call(`/api/state/${session.id}`,b.token)).photos.length,1);
  assert.equal((await fetch(`${base}/api/images/${photoA.id}`,{headers:{Authorization:`Bearer ${b.token}`}})).status,403);
  assert.equal((await fetch(`${base}/api/images/${photoA.id}`)).status,401);
  assert.equal((await fetch(`${base}/data/atividade.sqlite`)).status,404);
  assert.equal((await call(`/api/admin/session/${session.id}/phase`,admin,{phase:'results'})).status,409);
  for(const photo of [photoA,photoB])await call(`/api/admin/photos/${photo.id}`,admin,{status:'approved'});
  const opened=await call(`/api/admin/session/${session.id}/phase`,admin,{phase:'results'});
  assert.equal(opened.session.phase,'results');
  const result=await call(`/api/state/${session.id}`,a.token);
  assert.deepEqual(result.photos.filter(photo=>photo.status==='approved').map(photo=>photo.title),['Foto A','Foto B']);
  assert.equal((await fetch(`${base}/api/images/${photoB.id}`,{headers:{Authorization:`Bearer ${a.token}`}})).status,200);
  assert.equal((await call('/api/vote',b.token,{photoId:photoA.id})).status,404);
  const renewed=await call('/api/join',null,{sessionCode:session.code,accessCode:participants[1].code,groupId:groups[0].id});
  assert.equal(renewed.user.group_id,groups[1].id);
  assert.equal((await call(`/api/state/${session.id}`,b.token)).status,401);
});
